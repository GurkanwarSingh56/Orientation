/**
 * Returns list of client-facing questions for a domain without answer keys (Firebase / API ready)
 */
export function getClientQuestionsForDomain(domain: DomainSlug): ClientQuizQuestion[] {
  return ALL_QUIZ_QUESTIONS
    .filter((q) => q.domain === domain)
    .map(({ id, domain: d, question, options, difficulty, points }) => ({
      id,
      domain: d,
      question,
      options,
      difficulty,
      points,
    }));
}

/**
 * Evaluates quiz submission securely against answer key
 */
export function evaluateQuizSubmission(
  domain: DomainSlug,
  submissions: QuizSubmission[]
): QuizEvaluationResult {
  const domainQuestions = ALL_QUIZ_QUESTIONS.filter((q) => q.domain === domain);
  const totalQuestions = domainQuestions.length;

  let correctCount = 0;
  let earnedPoints = 0;
  let maxPoints = 0;

  const details = domainQuestions.map((q) => {
    maxPoints += q.points;
    const sub = submissions.find((s) => s.questionId === q.id);
    const selectedOption = sub ? sub.selectedOption : -1;
    const isCorrect = selectedOption === q.correctAnswer;

    if (isCorrect) {
      correctCount += 1;
      earnedPoints += q.points;
    }

    return {
      questionId: q.id,
      isCorrect,
      selectedOption,
      correctAnswer: q.correctAnswer,
      explanation: q.explanation,
    };
  });

  return {
    score: correctCount,
    maxScore: totalQuestions,
    totalPoints: maxPoints,
    earnedPoints,
    details,
  };
}
